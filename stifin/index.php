            <h4 class="fw-bold mb-3 text-center">Apa itu STIFIn?</h4>
            <p class="text-muted text-justify" style="text-align: justify;">
                STIFIn sendiri merupakan konsep tentang fungsi otak dominan yang menjadi sistem operasi pada otak manusia
                (Sensing, Thinking, Intuiting, Feeling, dan Insting). STIFIn juga merupakan metode untuk mengetahui jenis
                kecerdasan dan personaliti seseorang melalui Tes STIFIn.
                <br><br>
                Konsep STIFIn sudah dibangun oleh Farid Poniman sejak tahun 1999. Riset dan kajiannya sudah dilakukan lebih
                dari 20 tahun. Penerapan konsep STIFIn mulai digunakan ketika Farid Poniman bersama Indrawan Nugroho dan
                Jamil Azzaini mendirikan lembaga training bernama <strong>KUBIK Leadership</strong>
                (<a href="https://www.kubik.co.id" target="_blank">www.kubik.co.id</a>). Lembaga tersebut selalu memetakan
                peserta sesuai jenis kecerdasannya sebelum training dimulai. Sebagai konsep, STIFIn terus dikembangkan hingga
                akhirnya mematenkan formula 5 MK (Mesin Kecerdasan) dan 9 PG (Personaliti Genetik).
                <br><br>
                Yayasan STIFIn beruntung memiliki Konsep STIFIn dan alat Tes STIFIn. Sejak diperkenalkan kepada masyarakat
                pada Juni 2009, Tes STIFIn telah digunakan oleh hampir 500.000 orang (update 25 Maret 2023). Sebagian besar
                peserta tes mengakui tingkat akurasi alat Tes STIFIn yang tinggi. Hal ini juga dibuktikan oleh tim riset
                independen dari Malaysia yang dipimpin oleh <strong>Prof. Dr. Mohammed Zin Nurdin</strong> bersama
                <strong>Dr. Suhaimi Mohamad</strong> dan <strong>Dr. Wan Sulaiman</strong>, yang menunjukkan validitas dan
                reliabilitas Tes STIFIn yang tinggi. Keunggulan lainnya adalah konsep STIFIn terbukti aplikatif dalam berbagai
                bidang dan disiplin ilmu. Ini menjadi keuntungan besar bagi Yayasan STIFIn karena memiliki alat tes dan konsep
                yang <strong>Simple, Akurat, dan Aplikatif</strong>.
                <br><br>
                Sebagai bentuk aplikasinya, Konsep STIFIn telah dipraktikkan dalam menghafal Al-Qur'an oleh
                <strong>Rumah Qur'an STIFIn (RQS)</strong> melalui <em>Metode Tahfidz STIFIn</em>. Dengan metode ini, santri
                dapat menghafal 30 Juz dengan tingkat <em>mutqin</em> 15 Juz hanya dalam waktu sekitar 7 bulan.
                <br><br>
                Tes STIFIn dilakukan dengan cara memindai kesepuluh ujung jari Anda (kurang lebih 1–2 menit). Sidik jari yang
                membawa informasi tentang komposisi susunan saraf kemudian dianalisis dan dikaitkan dengan belahan otak yang
                dominan berperan sebagai sistem operasi dan mesin kecerdasan Anda.
            </p>

